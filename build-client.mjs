/**
 * Build the browser artifact for the DSH Figma Designer bundle.
 *
 * A Client half is one classic script that registers a lazy factory, so the
 * hand-written module under `client-src/` is concatenated into that factory's
 * scope. `React`/`h` come from the shell module table; nothing else is imported.
 *
 * Usage: node build-client.mjs
 */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const sourceDir = join(root, 'client-src')
const ORDER = ['card.js']
const PACKAGE_NAME = 'dsh-figma-designer'

const present = readdirSync(sourceDir).filter((name) => name.endsWith('.js'))
const missing = ORDER.filter((name) => !present.includes(name))
if (missing.length > 0) {
  console.error(`build-client: missing client-src file(s): ${missing.join(', ')}`)
  process.exit(1)
}
const extra = present.filter((name) => !ORDER.includes(name))
if (extra.length > 0) {
  console.error(`build-client: client-src file(s) not listed in ORDER: ${extra.join(', ')}`)
  process.exit(1)
}

const bodies = ORDER.map((name) => {
  const source = readFileSync(join(sourceDir, name), 'utf8').replace(/\s+$/, '')
  return `    // ---- client-src/${name} ----\n${source}\n`
}).join('\n')

const artifact = `/**
 * DSH Figma Designer — Client half (GENERATED by build-client.mjs).
 * Registers the Plugins-page card. Do not edit this file; change client-src/.
 */
window.__ModuleLoader__.load({
  id: '${PACKAGE_NAME}',
  factory(require) {
    const React = require('react')
    const h = React.createElement

${bodies}
    return {
      inject: ['slots'],
      apply(ctx) {
        FigmaDesignerCard.apply(ctx)
      },
    }
  },
})
`

writeFileSync(join(root, 'client.js'), artifact, 'utf8')
console.log(`build-client: wrote client.js (${artifact.split('\n').length} lines, ${ORDER.join(' + ')})`)
